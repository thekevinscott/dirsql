"""Glob speed: `node_modules` is an ordinary directory.

A tree where three quarters of the files sit in `node_modules` directories:
at the top, under source directories, and nested inside other
`node_modules`. `'./**/*.js'` and `'./**/node_modules/pkg/*.js'` enter them
at any depth, nested ones included, as bash globstar does. Natives are `find`,
`fd` and `rg --files` returning the same set. No mocks: real console script,
real process, real filesystem.
"""

from __future__ import annotations

import shutil

import pytest

from .speed_of_light import (
    Native,
    agreed_rows,
    assert_speed_of_light,
    baseline,
    cli,
    dirsql_rows,
    fd,
    grow_until_native_takes_a_second,
    paired,
    rg,
    shell_natives,
    startup_seconds,
    timed,
)

EVERY = [
    Native("find", ("find",), "{bin} . -type f -name '*.js' -printf '%P\\n'"),
    fd("--glob '*.js'"),
    rg("-g '*.js' -g '!.*'"),
]
NAMED = [
    Native(
        "find",
        ("find",),
        "{bin} . -regextype posix-extended -type f"
        " -regex '.*/node_modules/pkg/[^/]*\\.js' -printf '%P\\n'",
    ),
    fd("--full-path --glob '**/node_modules/pkg/*.js'"),
    rg("-g '**/node_modules/pkg/*.js' -g '!.*'"),
]
FANOUT = 8


def item(i):
    """Item `i`'s path and its area: 0 is source, 1 a `pkg` under a source
    directory's `node_modules`, 2 the top-level `node_modules`, 3 a `pkg`
    nested in another package's `node_modules`. Every sixth is `.json`."""
    j = i // 4
    nest = f"a{j % FANOUT}/b{j // FANOUT % FANOUT}/c{j // FANOUT**2 % FANOUT}"
    dep = f"dep{j // FANOUT**3 % FANOUT}"
    name = f"f{i}.json" if i % 6 == 0 else f"f{i}.js"
    area = i % 4
    folder = (
        f"src/{nest}",
        f"src/{nest}/node_modules/pkg",
        f"node_modules/{dep}/{nest}",
        f"src/{nest}/node_modules/{dep}/node_modules/pkg",
    )[area]
    return f"{folder}/{name}", area


def build_tree(root, lo, hi):
    for i in range(lo, hi):
        rel, _ = item(i)
        path = root / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.touch()


def matched(n, glob):
    areas = (0, 1, 2, 3) if glob == "./**/*.js" else (1, 3)

    def hit(i):
        rel, area = item(i)
        return area in areas and rel.endswith(".js")

    return sum(1 for i in range(n) if hit(i))


def describe_node_modules_glob_speed_of_light():
    @pytest.fixture(scope="module")
    def tree(tmp_path_factory):
        root = tmp_path_factory.mktemp("node-modules") / "tree"
        root.mkdir()
        try:
            n = grow_until_native_takes_a_second(
                lambda lo, hi: build_tree(root, lo, hi),
                baseline(shell_natives(root, EVERY)),
                start=100_000,
                ceiling=2**22,
            )
            yield root, n, startup_seconds()
        finally:
            shutil.rmtree(root, ignore_errors=True)

    @pytest.mark.parametrize(
        ("glob", "specs"),
        [
            ("./**/*.js", EVERY),
            ("./**/node_modules/pkg/*.js", NAMED),
        ],
    )
    def it_matches_native_files_within_the_bar(tree, glob, specs):
        root, n, startup = tree

        def dirsql(timeout):
            proc, seconds = timed(
                [cli(), "query", f"SELECT path FROM '{glob}'"],
                root,
                timeout=timeout,
            )
            return sorted(row for (row,) in dirsql_rows(proc, ("path",))), seconds

        result = paired(shell_natives(root, specs), dirsql, startup)
        expected, actual = agreed_rows(result), result.dirsql_rows
        assert len(expected) == matched(n, glob)

        assert actual == expected
        assert_speed_of_light(glob, result, startup)
