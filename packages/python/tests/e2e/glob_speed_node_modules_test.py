"""Glob speed: `node_modules` is an ordinary directory.

A tree where three quarters of the files sit in `node_modules` directories:
at the top, under source directories, and nested inside other
`node_modules`. `'./**/*.js'` and `'./**/node_modules/pkg/*.js'` enter them
at any depth, nested ones included, as bash globstar does. Native is `find`
returning the same set. No mocks: real console script, real process, real
filesystem.
"""

from __future__ import annotations

import shutil

import pytest

from .speed_of_light import (
    assert_speed_of_light,
    best_of,
    cli,
    dirsql_rows,
    dirsql_timeout,
    grow_until_native_takes_a_second,
    hopeless_seconds,
    startup_seconds,
    timed,
)

EVERY = "find . -type f -name '*.js' -printf '%P\\n'"
NAMED = (
    "find . -regextype posix-extended -type f"
    " -regex '.*/node_modules/pkg/[^/]*\\.js' -printf '%P\\n'"
)
FANOUT = 8


def item(i):
    """Item `i`'s path and its area: 0 is source, 1 a `pkg` under a source
    directory's `node_modules`, 2 the top-level `node_modules`, 3 a `pkg`
    nested in another package's `node_modules`. Every sixth is `.json`."""
    j = i // 4
    nest = f"a{j % FANOUT}/b{j // FANOUT % FANOUT}/c{j // FANOUT**2 % FANOUT}"
    dep = f"dep{j // FANOUT**3 % FANOUT}"
    name = f"f{i}.json" if i % 6 == 0 else f"f{i}.js"
    area = i % 4
    folder = (
        f"src/{nest}",
        f"src/{nest}/node_modules/pkg",
        f"node_modules/{dep}/{nest}",
        f"src/{nest}/node_modules/{dep}/node_modules/pkg",
    )[area]
    return f"{folder}/{name}", area


def build_tree(root, lo, hi):
    for i in range(lo, hi):
        rel, _ = item(i)
        path = root / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.touch()


def matched(n, glob):
    areas = (0, 1, 2, 3) if glob == "./**/*.js" else (1, 3)

    def hit(i):
        rel, area = item(i)
        return area in areas and rel.endswith(".js")

    return sum(1 for i in range(n) if hit(i))


def native(root, script):
    proc, seconds = timed(["bash", "-c", script], root, timeout=600)
    assert proc.returncode == 0, proc.stderr
    return sorted(proc.stdout.splitlines()), seconds


def describe_node_modules_glob_speed_of_light():
    @pytest.fixture
    def root(tmp_path):
        tree = tmp_path / "node-modules"
        tree.mkdir()
        try:
            yield tree
        finally:
            shutil.rmtree(tree, ignore_errors=True)

    @pytest.mark.parametrize(
        ("glob", "script"),
        [
            ("./**/*.js", EVERY),
            ("./**/node_modules/pkg/*.js", NAMED),
        ],
    )
    def it_matches_native_files_within_the_bar(root, glob, script):
        startup = startup_seconds()
        n = grow_until_native_takes_a_second(
            lambda lo, hi: build_tree(root, lo, hi),
            lambda: native(root, script),
            start=100_000,
            ceiling=2**22,
        )
        expected, native_seconds = best_of(lambda: native(root, script), "native")
        assert len(expected) == matched(n, glob)

        def dirsql():
            proc, seconds = timed(
                [cli(), "query", f"SELECT path FROM '{glob}'"],
                root,
                timeout=dirsql_timeout(native_seconds),
            )
            return sorted(row for (row,) in dirsql_rows(proc, ("path",))), seconds

        actual, dirsql_seconds = best_of(
            dirsql, "dirsql", hopeless_seconds(native_seconds, startup)
        )

        assert actual == expected
        assert_speed_of_light(glob, native_seconds, dirsql_seconds, startup)
